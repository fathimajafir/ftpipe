from __future__ import annotations

import os
import shutil

from .base import Provider, ProviderError

TEMPLATE = '''"""Generated by ftpipe. LoRA fine-tune for {base_model}.

Install:  pip install "ftpipe[local]"
Run:      python train_lora.py
"""

import json

from datasets import load_dataset
from peft import LoraConfig
from transformers import AutoModelForCausalLM, AutoTokenizer
from trl import SFTConfig, SFTTrainer

DATA = "{train_path}"
OUT = "{out_dir}"
BASE = "{base_model}"

tokenizer = AutoTokenizer.from_pretrained(BASE)
if tokenizer.pad_token is None:
    tokenizer.pad_token = tokenizer.eos_token


def to_text(row):
    messages = row["messages"]
    return {{"text": tokenizer.apply_chat_template(messages, tokenize=False)}}


dataset = load_dataset("json", data_files={{DATA: "train"}})["train"].map(to_text)

model = AutoModelForCausalLM.from_pretrained(BASE, device_map="auto")

trainer = SFTTrainer(
    model=model,
    train_dataset=dataset,
    peft_config=LoraConfig(r={lora_r}, lora_alpha={lora_alpha}, lora_dropout=0.05, task_type="CAUSAL_LM"),
    args=SFTConfig(
        output_dir=OUT,
        num_train_epochs={epochs},
        per_device_train_batch_size={batch_size},
        learning_rate={learning_rate},
        logging_steps=10,
        save_strategy="epoch",
        dataset_text_field="text",
    ),
)
trainer.train()
trainer.save_model(OUT)
tokenizer.save_pretrained(OUT)
print("saved adapter to", OUT)
'''


class LocalProvider(Provider):
    """Local LoRA fine-tuning on your own GPU.

    This provider does not train from inside the pipeline (that needs torch).
    `finetune` writes a ready-to-run script plus the exported data, so you run
    one command on the box that has the GPU.
    """

    name = "local"
    supports_validation_file = False
    supports_finetune = True

    def export(self, records, out_path, with_validation=False):
        from ..data import write_jsonl

        return write_jsonl(records, out_path, mapper=lambda r: {"messages": r.messages})

    def finetune(self, train_path, val_path, hyperparams, cfg):
        run_dir = cfg.run_dir()
        target = os.path.join(run_dir, "local")
        os.makedirs(target, exist_ok=True)
        local_train = os.path.join(target, "train.jsonl")
        shutil.copyfile(train_path, local_train)

        script = os.path.join(target, "train_lora.py")
        with open(script, "w", encoding="utf-8") as handle:
            handle.write(
                TEMPLATE.format(
                    base_model=cfg.get("finetune.base_model", "Qwen/Qwen2.5-1.5B-Instruct"),
                    train_path=local_train,
                    out_dir=os.path.join(target, "adapter"),
                    epochs=float(hyperparams.get("epochs", 3)),
                    batch_size=int(hyperparams.get("batch_size", 2)),
                    learning_rate=float(hyperparams.get("learning_rate", 0.0002)),
                    lora_r=int(hyperparams.get("lora_r", 16)),
                    lora_alpha=int(hyperparams.get("lora_alpha", 32)),
                )
            )
        print("[local] wrote %s" % script)
        print("[local] run it on a GPU machine:  python %s" % script)
        return {
            "provider": self.name,
            "job_id": "local-script",
            "model": None,
            "status": "script_written",
            "script": script,
            "note": "run the generated script, then serve the adapter (vLLM/Ollama) and evaluate via that endpoint",
        }

    def generate(self, model, messages, temperature=0.0, max_tokens=256):
        raise ProviderError(
            "local: this pipeline does not host models. Serve your adapter (e.g. vLLM with an "
            "OpenAI-compatible endpoint) and evaluate it through that provider instead."
        )
